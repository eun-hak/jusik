export function plannerUserPrompt(
  topic: { keyword: string; description: string },
  existingTitles: string[],
): string {
  return `오늘의 글감:
- 키워드: ${topic.keyword}
- 설명: ${topic.description}

기존 발행 글 제목 (중복/겹침 방지):
${existingTitles.slice(0, 30).map((t) => `- ${t}`).join("\n")}

위 주제로 블로그 글 1편을 기획해줘.

아래 JSON 형식으로 응답:
{
  "title": "메인 키워드 | 설명형 보조 문구",
  "seoKeyword": "메인 SEO 키워드",
  "subKeywords": ["서브1", "서브2", "서브3", "서브4", "서브5"],
  "category": "카테고리명",
  "slug": "english-slug-with-hyphens",
  "structure": ["섹션1 소제목", "섹션2 소제목", "섹션3 소제목", "섹션4 소제목", "섹션5 소제목", "핵심 정리", "FAQ"],
  "searchIntent": "이 글을 검색할 독자의 의도 한 문장",
  "targetQuestion": "독자가 가장 궁금해할 핵심 질문"
}`;
}

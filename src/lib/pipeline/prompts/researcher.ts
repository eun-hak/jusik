import type { PlanResult } from "../types";

export const RESEARCHER_SYSTEM = `너는 주식 시장을 가르치는 "투자 교육 전문가"이다.

목표:
블로그 콘텐츠 제작을 위한 배경 지식을 정리한다.
작가가 글을 쓸 수 있도록 정확하고 구조적인 자료를 제공한다.

설명 방식:
모든 답변은 아래 구조를 반드시 따른다:
1. 한 줄 핵심 요약
2. 개념 설명
3. 왜 중요한지
4. 실제 시장에서 어떻게 나타나는지
5. 초보 투자자가 헷갈리는 포인트
6. 관련 개념 비교

규칙:
- 블로그 글을 작성하지 않는다 (자료 정리만)
- 투자 추천, 종목 매수/매도 조언 금지
- 감정적 표현 없이 구조적으로 설명
- 가능하면 표 형태로 비교 정리
- 핵심 공식이나 수치가 있으면 명확히 제시
- "왜 그런지"를 반드시 포함
- 불필요한 서론 없이 바로 핵심부터

한국어로 답변한다.`;

export function researcherUserPrompt(plan: PlanResult): string {
  return `다음 주제에 대해 블로그 글 작성용 배경 지식을 정리해줘.

주제: ${plan.title}
핵심 질문: ${plan.targetQuestion}
SEO 키워드: ${plan.seoKeyword}
서브 키워드: ${plan.subKeywords.join(", ")}

다뤄야 할 섹션:
${plan.structure.map((s, i) => `${i + 1}. ${s}`).join("\n")}

위 섹션 순서에 맞게 각각에 대한 배경 지식을 정리해줘.
특히 다음을 포함:
- 핵심 개념의 정확한 정의
- 왜 중요한지 (시장 관점)
- 초보자가 흔히 오해하는 부분
- 관련 개념 간 비교 (있다면)
- 실제 시장에서의 사례나 수치 (있다면)`;
}
